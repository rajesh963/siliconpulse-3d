const DEL = (maturity: IPDeliverables['maturity'], coverage: number): IPDeliverables => ({
  rtlFrozen: true,
  lintClean: maturity !== 'v0.1 Arch',
  spyglassCdcClean: coverage >= 90,
  jasperGoldVerified: coverage >= 85,
  upfPowerIntent: true,
  timingClosed: maturity === 'v1.0 Tapeout' || maturity === 'v0.9 Timing Final',
  uvmCoveragePercent: coverage,
  maturity
});

interface IpSpec {
  id: string;
  name: string;
  displayName: string;
  description: string;
  category: ModuleNode['category'];
  type?: ModuleNode['type'];
  level: number;
  parentId: string;
  x?: number;
  z?: number;
  w: number;
  d: number;
  h?: number;
  color: string;
  clocks?: string[];
  resets?: string[];
  powerDomains?: string[];
  instances?: string[];
  ports?: Port[];
  deliverables?: IPDeliverables;
  docRef?: string;
  shortLabel?: string;
  subtitle?: string;
  role?: ModuleNode['role'];
  children?: ModuleNode[];
}

const IP = (spec: IpSpec): ModuleNode => {
  const height = spec.h ?? 0.8;
  return {
    id: spec.id,
    name: spec.name,
    displayName: spec.displayName,
    description: spec.description,
    type: spec.type ?? 'ip',
    category: spec.category,
    level: spec.level,
    parentId: spec.parentId,
    position: [spec.x ?? 0, height / 2, spec.z ?? 0],
    size: [spec.w, height, spec.d],
    color: spec.color,
    clockDomains: spec.clocks ?? ['F_SRI_500M'],
    resetDomains: spec.resets ?? ['rst_aurix_n'],
    powerDomains: spec.powerDomains,
    instances: spec.instances,
    ports: spec.ports ?? [],
    deliverables: spec.deliverables,
    docRef: spec.docRef,
    shortLabel: spec.shortLabel,
    subtitle: spec.subtitle,
    role: spec.role,
    children: spec.children,
  };
};

