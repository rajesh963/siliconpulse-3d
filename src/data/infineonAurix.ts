interface MicroSpec {
  id: string;
  name: string;
  displayName: string;
  description: string;
  color: string;
  category?: ModuleNode['category'];
  type?: ModuleNode['type'];
  docRef?: string;
  ports?: Port[];
}

const microGrid = (
  parentId: string,
  specs: MicroSpec[],
  cols: number,
  w: number,
  d: number
): ModuleNode[] => {
  const rows = Math.ceil(specs.length / cols);
  return specs.map((spec, index) => {
    const row = Math.floor(index / cols);
    const col = index % cols;
    const itemsInRow = Math.min(cols, specs.length - row * cols);
    return IP({
      id: spec.id,
      name: spec.name,
      displayName: spec.displayName,
      description: spec.description,
      category: spec.category ?? 'compute',
      type: spec.type ?? 'submodule',
      level: 3,
      parentId,
      x: (col - (itemsInRow - 1) / 2) * (w + 0.18),
      z: (row - (rows - 1) / 2) * (d + 0.18),
      w,
      d,
      h: 0.42,
      color: spec.color,
      clocks: ['F_SRI_500M'],
      docRef: spec.docRef,
      ports: spec.ports ?? [],
    });
  });
};

