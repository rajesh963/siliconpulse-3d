// Propagate power/reset membership from clusters down to IPs and microarch blocks.
const applyDomainInheritance = (
  node: ModuleNode,
  inheritedPower: string[],
  inheritedResets: string[]
) => {
  if (!node.powerDomains || node.powerDomains.length === 0) {
    node.powerDomains = [...inheritedPower];
  }
  const usesDefaultReset =
    node.resetDomains.length === 1 && node.resetDomains[0] === 'rst_aurix_n';
  if (usesDefaultReset) {
    node.resetDomains = [...inheritedResets];
  }

  for (const child of node.children ?? []) {
    applyDomainInheritance(
      child,
      node.powerDomains ?? inheritedPower,
      node.resetDomains.length > 0 ? node.resetDomains : inheritedResets
    );
  }
};

applyDomainInheritance(
  INF_HIERARCHY,
  INF_POWER.map(domain => domain.name),
  INF_RESETS.map(domain => domain.name)
);

